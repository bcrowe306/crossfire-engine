#!/usr/bin/env bash
# The engine's profiling harness: plays scenes of a project in a Spall build of the player,
# headless, and reports where each frame's time goes (tools/spall_report). The microbenchmarks
# (bench/main.odin) stay for single costs; this measures whole frames of a real game.
#
#   tools/profile_game.sh [options] <project folder> [scene...]   (default: the start scene)
#     --seconds <s>       how long each run plays (default 10; the first 60 frames are warm-up)
#     --runs <n>          runs per scene (default 3; reported together, their frames pooled)
#     --renderer <name>   the player's --renderer (default gpu; software, vulkan, opengl...)
#     --cpus <list>       taskset's CPU list (default 2-5; "" for none)
#     --clock <wall|cpu>  the trace's clock (default wall): cpu is each thread's CPU time, which
#                         leaves out time the thread was descheduled (other programs' load), its
#                         GPU waits and sleeps: for comparing CPU work on a busy machine
#     --wait-quiet <s>    before each run, wait up to that long (default 300; 0: don't) for the
#                         machine's CPU use to drop under --quiet-busy percent (default 20): a
#                         compile or another program sharing the CPUs slows a run by 10-60%
#     --auto              build with SPALL_AUTO (every procedure: slow, for finding hot spots)
#     --no-build          use the last build
#     --save-baseline     keep the results as the baseline (build/profile_game/baseline/)
#     --compare           compare with the baseline; exit 1 if a scene's mean frame got
#                         slower by more than --threshold percent (default 5)
#     --threshold <pct>
#
# Each run plays a fresh copy of the project (its build/ and export/ left out) with its own
# XDG_DATA_HOME (saves land there, never in your own), on SDL's offscreen video driver and the
# dummy audio driver (no window, no sound, nothing from the desktop), on pinned CPUs. Nobody
# presses keys: the scene plays as it starts (scripts, physics, animations, particles, lighting).
#
# A project with scripts gets a player with them, as the editor's Play makes one: a generated
# main in build/profile_game/player/ importing the project's `scripts` package.
#
# Results: build/profile_game/results/<scene>.txt, .json and .spall (open it in Spall:
# https://gravitymoth.com/spall/). Example, from the workspace:
#
#   odin_sdl_engine/tools/profile_game.sh odin_sdl_editor/examples/demo_project ForestScene LairScene
set -euo pipefail

ENGINE=$(cd "$(dirname "$0")/.." && pwd)
ODIN=${ODIN:-odin}
OUT=$ENGINE/build/profile_game
SECONDS_=10
RUNS=3
RENDERER=gpu
CPUS=2-5
CLOCK=wall
WAIT_QUIET=300
QUIET_BUSY=20
AUTO=0
BUILD=1
SAVE=0
COMPARE=0
THRESHOLD=5
PROJECT=""
SCENES=()

while [[ $# -gt 0 ]]; do
	case $1 in
		--seconds) SECONDS_=$2; shift 2 ;;
		--runs) RUNS=$2; shift 2 ;;
		--renderer) RENDERER=$2; shift 2 ;;
		--cpus) CPUS=$2; shift 2 ;;
		--clock) CLOCK=$2; shift 2 ;;
		--wait-quiet) WAIT_QUIET=$2; shift 2 ;;
		--quiet-busy) QUIET_BUSY=$2; shift 2 ;;
		--auto) AUTO=1; shift ;;
		--no-build) BUILD=0; shift ;;
		--save-baseline) SAVE=1; shift ;;
		--compare) COMPARE=1; shift ;;
		--threshold) THRESHOLD=$2; shift 2 ;;
		-h|--help) sed -n '2,39p' "$0"; exit 0 ;;
		-*) echo "profile_game.sh: unknown option $1" >&2; exit 2 ;;
		*) if [[ -z $PROJECT ]]; then PROJECT=$1; else SCENES+=("$1"); fi; shift ;;
	esac
done
[[ -n $PROJECT && -f $PROJECT/project.xml ]] || { echo "usage: tools/profile_game.sh [options] <project folder> [scene...]" >&2; exit 2; }
PROJECT=$(cd "$PROJECT" && pwd)
if [[ ${#SCENES[@]} -eq 0 ]]; then
	SCENES=("$(sed -n 's/.*startScene="\([^"]*\)".*/\1/p' "$PROJECT/project.xml" | head -1)")
fi

mkdir -p "$OUT/results" "$OUT/runs" "$OUT/player"
PLAYER=$OUT/player_bin
REPORT=$OUT/spall_report

if [[ $BUILD -eq 1 ]]; then
	scripts=0
	compgen -G "$PROJECT/scripts/*.odin" >/dev/null && scripts=1
	{
		echo "// Generated by tools/profile_game.sh: the player, with the project's scripts when it has them"
		echo "package profile_player"
		echo
		echo "@(require) import \"base:runtime\""
		echo "import e \"engine:.\""
		[[ $scripts -eq 1 ]] && echo "import scripts \"project:scripts\"" && echo "_ :: scripts"
		echo
		echo "main :: proc() {"
		echo "	e.Player_Main()"
		echo "}"
		echo
		echo "when e.SPALL && e.SPALL_AUTO {"
		echo "	@(instrumentation_enter)"
		echo "	traceEnter :: proc \"contextless\" (proc_address, call_site_return_address: rawptr, loc: runtime.Source_Code_Location) {"
		echo "		e.Trace_AutoEnter(loc)"
		echo "	}"
		echo "	@(instrumentation_exit)"
		echo "	traceExit :: proc \"contextless\" (proc_address, call_site_return_address: rawptr, loc: runtime.Source_Code_Location) {"
		echo "		e.Trace_AutoExit()"
		echo "	}"
		echo "}"
	} >"$OUT/player/main.odin"
	defines=(-define:SPALL=true)
	[[ $AUTO -eq 1 ]] && defines+=(-define:SPALL_AUTO=true)
	echo "Building the player with ${defines[*]} (-o:speed)..."
	"$ODIN" build "$OUT/player" "-collection:engine=$ENGINE" "-collection:project=$PROJECT" \
		"${defines[@]}" -o:speed "-out:$PLAYER"
fi
if [[ ! -x $REPORT || $ENGINE/tools/spall_report/main.odin -nt $REPORT ]]; then
	"$ODIN" build "$ENGINE/tools/spall_report" -o:speed "-out:$REPORT"
fi
[[ -x $PLAYER ]] || { echo "profile_game.sh: no player at $PLAYER (run without --no-build)" >&2; exit 1; }

load=$(cut -d' ' -f1 /proc/loadavg)
cpus=$(nproc)
if awk -v l="$load" -v c="$cpus" 'BEGIN { exit !(l > c / 4) }'; then
	echo "Warning: load average $load on $cpus CPUs: other work may skew the numbers"
fi
pin=()
[[ -n $CPUS ]] && command -v taskset >/dev/null && pin=(taskset -c "$CPUS")

# The machine's CPU use (percent of all CPUs) over one second, from /proc/stat
cpuBusy() {
	local a b
	read -r -a a < <(grep '^cpu ' /proc/stat)
	sleep 1
	read -r -a b < <(grep '^cpu ' /proc/stat)
	local idle=$(( (b[4] + b[5]) - (a[4] + a[5]) ))
	local total=0 i
	for i in 1 2 3 4 5 6 7 8; do total=$(( total + b[i] - a[i] )); done
	(( total > 0 )) || { echo 0; return; }
	echo $(( 100 * (total - idle) / total ))
}

# Waits (at most $WAIT_QUIET seconds) until the machine's CPU use is under $QUIET_BUSY percent,
# so a run doesn't share the CPUs with other work; says when it gave up
waitQuiet() {
	(( WAIT_QUIET > 0 )) || return 0
	local waited=0 busy
	while :; do
		busy=$(cpuBusy)
		(( busy < QUIET_BUSY )) && return 0
		if (( waited >= WAIT_QUIET )); then
			echo "  (the machine stayed busy: ${busy}% of its CPUs in use; running anyway)"
			return 0
		fi
		(( waited == 0 )) && echo "  waiting for the machine to be quiet (${busy}% of its CPUs in use)..."
		sleep 4
		waited=$(( waited + 5 ))
	done
}

status=0
summary=()
for scene in "${SCENES[@]}"; do
	# A failed run must not leave the last results looking like this one's
	rm -rf "$OUT/runs/$scene" "$OUT/results/$scene".*
	medians=()
	for run in $(seq 1 "$RUNS"); do
		dir=$OUT/runs/$scene/$run
		rm -rf "$dir"
		mkdir -p "$dir/data"
		# The project as it is, without build output
		(cd "$PROJECT" && tar -c --exclude=./build --exclude=./export --exclude=./.git .) | (mkdir -p "$dir/project" && tar -x -C "$dir/project")
		waitQuiet
		echo "[$scene $run/$RUNS] playing ${SECONDS_} s ($RENDERER)"
		if ! env SDL_VIDEO_DRIVER=offscreen SDL_AUDIO_DRIVER=dummy XDG_DATA_HOME="$dir/data" \
			SPALL_TRACE="$dir/trace.spall" SPALL_CLOCK="$CLOCK" timeout $((SECONDS_ + 120)) "${pin[@]}" "$PLAYER" "$dir/project" \
			--scene "$scene" --quit-after "$SECONDS_" --renderer "$RENDERER" >"$dir/log.txt" 2>&1; then
			echo "[$scene $run/$RUNS] the player failed: $dir/log.txt"
			tail -5 "$dir/log.txt"
			status=1
			continue
		fi
		if ! "$REPORT" "$dir/trace.spall" -skip=60 -json="$dir/report.json" >"$dir/report.txt" 2>&1; then
			echo "[$scene $run/$RUNS] no report:"; cat "$dir/report.txt"; status=1; continue
		fi
		p50=$(grep -o '"p50_ms": *[0-9.e+-]*' "$dir/report.json" | head -1 | sed 's/.*: *//' | xargs printf '%.3f')
		medians+=("$p50 $run")
		echo "[$scene $run/$RUNS] median frame $p50 ms"
	done
	[[ ${#medians[@]} -gt 0 ]] || continue
	# The report pools every run's frames and spans; the trace kept for Spall's viewer is the run
	# with the median frame
	traces=()
	for m in "${medians[@]}"; do traces+=("$OUT/runs/$scene/${m#* }/trace.spall"); done
	"$REPORT" "${traces[@]}" -skip=60 -json="$OUT/results/$scene.json" >"$OUT/results/$scene.txt" 2>&1 || status=1
	kept=$(printf '%s\n' "${medians[@]}" | sort -g | awk -v n=${#medians[@]} 'NR == int((n + 1) / 2) { print $2 }')
	cp "$OUT/runs/$scene/$kept/trace.spall" "$OUT/results/$scene.spall"
	all=$(printf '%s\n' "${medians[@]}" | cut -d' ' -f1 | sort -g | tr '\n' ' ')
	pooled=$(grep -o '"mean_ms": *[0-9.e+-]*' "$OUT/results/$scene.json" | head -1 | sed 's/.*: *//' | xargs printf '%.3f')
	summary+=("$(printf '%-14s mean frame %s ms over %s runs; median per run (ms): %s' "$scene" "$pooled" "${#medians[@]}" "$all")")
	if [[ $SAVE -eq 1 ]]; then
		mkdir -p "$OUT/baseline"
		cp "$OUT/results/$scene.json" "$OUT/baseline/$scene.json"
	fi
	if [[ $COMPARE -eq 1 ]]; then
		if [[ -f $OUT/baseline/$scene.json ]]; then
			echo
			echo "=== $scene: baseline -> now"
			"$REPORT" compare "$OUT/baseline/$scene.json" "$OUT/results/$scene.json" -threshold="$THRESHOLD" || status=1
		else
			echo "[$scene] no baseline to compare with (--save-baseline)"
		fi
	fi
done

echo
echo "Summary (results in build/profile_game/results/):"
for line in "${summary[@]}"; do echo "  $line"; done
for scene in "${SCENES[@]}"; do
	[[ -f $OUT/results/$scene.txt ]] && { echo; echo "=== $scene"; sed -n '1,30p' "$OUT/results/$scene.txt"; }
done
exit $status
